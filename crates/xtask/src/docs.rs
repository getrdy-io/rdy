//! `cargo xtask docs`: writes the generated Markdown pages under `docs/`.
//!
//! Only `docs/src/content/docs/` is published by Starlight. Generated pages live there too
//! (docs/plan/09-docs-site.md, sections 2 and 5).
//!
//! This build writes one placeholder page. It proves the write and check path. The schema-driven
//! spec reference (M1-022, M1-076) replaces the placeholder with real content.

use std::path::Path;

use anyhow::Result;

use crate::generate::{self, Generated};

/// The pages this build generates.
pub fn pages() -> Vec<Generated> {
    vec![Generated {
        path: "docs/src/content/docs/reference/spec/index.md",
        contents: SPEC_REFERENCE.to_owned(),
    }]
}

/// Writes the pages, or checks them when `check` is set. Returns `Ok(true)` when the run passes.
pub fn run(root: &Path, check: bool) -> Result<bool> {
    generate::run(root, check, "docs", &pages())
}

/// The placeholder for the spec reference. Frontmatter comes first, because Starlight reads it
/// only at the start of the file. The generated-file banner follows it.
const SPEC_REFERENCE: &str = r#"---
title: Spec reference
description: The rdy/v1 spec fields. This page is generated.
---

<!-- Generated by cargo xtask docs. Do not edit. -->

You can use this page to look up each `rdy/v1` spec field. The page is a placeholder for now.

The schema generator and the field renderer fill it in. They ship in M1-022 and M1-076. Until then,
read `docs/plan/01-spec-format.md` for the field list.
"#;

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_page_is_markdown_under_the_docs_tree() {
        for page in pages() {
            assert!(page.path.starts_with("docs/"), "{}", page.path);
            assert!(page.path.ends_with(".md"), "{}", page.path);
        }
    }

    #[test]
    fn every_page_starts_frontmatter_and_carries_the_banner() {
        for page in pages() {
            assert!(page.contents.starts_with("---\n"), "{}", page.path);
            assert!(
                page.contents
                    .contains("<!-- Generated by cargo xtask docs. Do not edit. -->"),
                "{}",
                page.path
            );
        }
    }

    #[test]
    fn render_is_deterministic() {
        assert_eq!(pages(), pages());
    }
}
